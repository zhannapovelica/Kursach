package com.example.kurs.chatbot.controller;

import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RestController;
import java.util.Map;

@RestController
public class ChatBotController {
    @PostMapping("/chat")
    public Map<String, String> analyzeMessage(@RequestBody Map<String, String> request) {
        String message = request.get("message").toLowerCase();

        if (message.contains("допомога")) {
            return Map.of("response", "Бот: Вам потрібна допомога? Я можу направити вас до спеціаліста.");
        } else if (message.contains("контакти")) {
            return Map.of("response", "Бот: Ось контакти нашої підтримки: +380 123 456 789.");
        }

        else if (message.contains("я відчуваю стрес і тривогу. що мені робити?")) {
            return Map.of("response", "Бот: Стрес і тривога — це природні реакції на напружені ситуації. Спробуйте використати техніки релаксації, такі як глибоке дихання або медитація. Це може допомогти заспокоїтись. Якщо стрес триває довго і починає впливати на ваше здоров'я, важливо звернутися до психолога чи психотерапевта для підтримки.");
        }
        else if (message.contains("як допомогти членам родини, які переживають після бойових дій?")) {
            return Map.of("response", "Бот: Слухайте та підтримуйте своїх близьких. Іноді найкраща допомога полягає в тому, щоб бути поряд і дати людині можливість говорити про свої переживання. Якщо їхня тривога чи стрес тривають, рекомендуємо звернутися до фахівця для консультацій та терапії.");
        }
        else if (message.contains("як справлятися з почуттям провини за те, що я вижив?")) {
            return Map.of("response", "Бот: Виживання після травматичного досвіду може викликати складні емоції, включаючи почуття провини. Важливо розуміти, що ці почуття є нормальними, але вони не означають, що ви не заслуговуєте на допомогу чи щастя. Психотерапія може допомогти вам обробити ці емоції.");
        }
        else if (message.contains("я відчуваю відчуження від інших людей після служби. Це нормально?")) {
            return Map.of("response", "Бот: Відчуження є поширеним переживанням серед ветеранів, оскільки адаптація до цивільного життя може бути складною. Важливо розуміти, що це не означає, що з вами щось не так. Бесіди з іншими ветеранами чи фахівцями можуть допомогти адаптуватися та знову знайти зв'язок з іншими.");
        }
        else if (message.contains("що робити, якщо я відчуваю, що не можу контролювати свою агресію?")) {
            return Map.of("response", "Бот: Якщо ви відчуваєте, що агресія виходить з-під контролю, спробуйте використовувати техніки самоконтролю, такі як фізичні вправи або глибоке дихання. Важливо звернутися до психолога, який може допомогти з вивченням методів управління емоціями та агресією.");
        }
        else if (message.contains("як зрозуміти, чи маю я посттравматичний стресовий розлад (ПТСР)?")) {
            return Map.of("response", "Бот: ПТСР може проявлятися через повторювані спогади про травматичні події, кошмари, сильний стрес або емоційну відчуженість. Якщо ви помітили ці симптоми у себе, важливо звернутися до психолога чи психіатра для діагностики та підтримки.");
        }
        else if (message.contains("як можна допомогти дітям, чиї батьки пережили бойові дії?")) {
            return Map.of("response", "Бот: Дітям може бути важко зрозуміти переживання батьків. Важливо створити безпечне та підтримуюче середовище, де діти можуть відкрито говорити про свої почуття. Якщо є труднощі у спілкуванні, фахівці можуть допомогти знайти підхід до дітей через гру або творчі методи.");
        }
        else if (message.contains("я відчуваю втому та виснаження, не можу зібратися з силами. Що робити?")) {
            return Map.of("response", "Бот: Хронічна втома може бути ознакою стресу або депресії. Спробуйте встановити режим сну, відпочинку та фізичної активності. Якщо втома триває, варто звернутися до лікаря чи психолога для з'ясування причин і отримання допомоги.");
        }
        else if (message.contains("що робити, якщо я відчуваю, що мої близькі не розуміють, через що я проходжу?")) {
            return Map.of("response", "Бот: Це може бути важким для вас і ваших близьких. Спробуйте пояснити їм свої почуття, щоб вони краще розуміли вашу ситуацію. Іноді спільні консультації з психологом можуть допомогти всім членам родини зрозуміти, як підтримати один одного.");
        }
        else {
            return Map.of("response", "Бот: Вибачте, я не розумію. Спробуйте запитати інакше.");
        }
    }
}
